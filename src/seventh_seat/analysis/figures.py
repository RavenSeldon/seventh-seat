"""Draft figures as dependency-free SVG (the project is standard-library only).

Every plotted number comes from the analysis results, which is itself
recomputed from the event records. These are working figures for the weekend;
they are regenerated by the same command as the numbers.
"""
from __future__ import annotations

from ..world.params import CELLS

W, H = 720, 300
MARGIN = 70
FONT = "font-family='ui-monospace,monospace' font-size='11'"
LABEL = "descriptive"  # marker used where a panel is descriptive, not causal


def _scale(values, lo=None, hi=None):
    lo = min(values) if lo is None else lo
    hi = max(values) if hi is None else hi
    if lo > 0:
        lo = 0
    if hi < 0:
        hi = 0
    if hi - lo < 1e-9:
        hi = lo + 1
    return lo, hi


def _x(value, lo, hi, width):
    return MARGIN + (value - lo) / (hi - lo) * width


def _svg(body, height=H):
    return (f"<svg xmlns='http://www.w3.org/2000/svg' width='{W}' height='{height}' "
            f"viewBox='0 0 {W} {height}'>\n"
            f"<rect width='{W}' height='{height}' fill='#fbfbfd'/>\n{body}</svg>\n")


def figure_contrasts(results):
    """Point estimates with scenario-cluster bootstrap 95% intervals."""
    rows = [("E", "Effect of E (evidence)"), ("S", "Effect of S (escalation route)"),
            ("ExS", "Interaction E x S (exploratory)")]
    data = results["contrasts"]["shortfall"]
    if data["E"]["estimate"] is None:
        return _svg(f"<text x='30' y='60' {FONT}>No complete scenario blocks; contrasts unavailable.</text>")
    values = [data[k]["estimate"] for k, _ in rows] + \
             [x for k, _ in rows for x in data[k]["ci95"]]
    lo, hi = _scale(values)
    width = W - 2 * MARGIN
    body = [f"<text x='{MARGIN}' y='30' {FONT} font-size='14'>"
            f"Downstream shortfall: contrasts with 95% cluster-bootstrap intervals "
            f"(n={data['E']['blocks']} scenarios)</text>"]
    zero = _x(0, lo, hi, width)
    body.append(f"<line x1='{zero}' y1='50' x2='{zero}' y2='{H - 40}' stroke='#999' "
                f"stroke-dasharray='3 3'/>")
    y = 80
    for key, label in rows:
        est, (a, b) = data[key]["estimate"], data[key]["ci95"]
        xa, xb, xe = _x(a, lo, hi, width), _x(b, lo, hi, width), _x(est, lo, hi, width)
        body.append(f"<text x='10' y='{y + 4}' {FONT}>{label}</text>")
        body.append(f"<line x1='{xa}' y1='{y}' x2='{xb}' y2='{y}' stroke='#334' "
                    f"stroke-width='2'/>")
        body.append(f"<rect x='{xa - 2}' y='{y - 6}' width='4' height='12' fill='#334'/>")
        body.append(f"<rect x='{xb - 2}' y='{y - 6}' width='4' height='12' fill='#334'/>")
        body.append(f"<circle cx='{xe}' cy='{y}' r='5' fill='#7b5ea7'/>")
        body.append(f"<text x='{xb + 10}' y='{y + 4}' {FONT}>{est:+.3g} "
                    f"[{a:+.3g}, {b:+.3g}]</text>")
        y += 60
    body.append(f"<text x='{MARGIN}' y='{H - 12}' {FONT} fill='#666'>"
                f"0 at dashed line; water units</text>")
    return _svg("\n".join(body))


def figure_shortfall(results):
    """Mean shortfall by cell, with the share of zero-shortfall episodes marked."""
    eps = results["episodes"]
    stats = {}
    for c in CELLS:
        outs = [e["outcome"] for e in eps.values()
                if e["evaluable"] and e["condition"] == c]
        if outs:
            stats[c] = (sum(o["shortfall"] for o in outs) / len(outs),
                        sum(o["shortfall"] == 0 for o in outs) / len(outs))
    values = [m for m, _ in stats.values()] or [0]
    lo, hi = _scale(values, lo=0)
    width = W - 2 * MARGIN
    body = [f"<text x='{MARGIN}' y='30' {FONT} font-size='14'>"
            f"Mean downstream shortfall by cell; dot = share of zeros</text>"]
    step = width // len(CELLS)
    for i, c in enumerate(CELLS):
        if c not in stats:
            continue
        mean_s, zero_share = stats[c]
        bar_h = (mean_s - lo) / (hi - lo) * (H - 120)
        x = MARGIN + i * step + 20
        body.append(f"<rect x='{x}' y='{H - 60 - bar_h}' width='{step - 60}' "
                    f"height='{bar_h}' fill='#7b5ea7'/>")
        body.append(f"<circle cx='{x + 8}' cy='{H - 60 - zero_share * (H - 120)}' "
                    f"r='4' fill='#c25e4e'/>")
        body.append(f"<text x='{x}' y='{H - 42}' {FONT}>{c}</text>")
        body.append(f"<text x='{x}' y='{H - 66 - bar_h}' {FONT}>{mean_s:.3g}</text>")
        body.append(f"<text x='{x + 16}' y='{H - 56 - zero_share * (H - 120)}' {FONT} "
                    f"fill='#c25e4e'>{zero_share:.0%}</text>")
    return _svg("\n".join(body))


def figure_ladder(results):
    """Witness ladder: first failed stage by cell (01 §9). Descriptive only."""
    dist = results["descriptive"]["witness_ladder_first_failed_stage_by_cell"]
    body = [f"<text x='{MARGIN}' y='30' {FONT} font-size='14'>"
            f"Witness ladder: first failed stage by cell ({LABEL}, not causal)</text>"]
    width = W - 2 * MARGIN
    step = width // len(CELLS)
    totals = {c: sum(d.values()) for c, d in dist.items()}
    for i, c in enumerate(CELLS):
        d = dist.get(c, {})
        y = H - 60
        total = totals.get(c) or 1
        palette = {"1": "#c25e4e", "2": "#d08a4e", "3": "#d0b44e", "4": "#8aa84e",
                   "5": "#4ea87b", "6": "#4e7ba8", "7": "#7b5ea7", "None": "#bbbbbb"}
        for stage, count in sorted(d.items(), key=lambda kv: (kv[0] == "None", kv[0])):
            h = count / total * (H - 120)
            y -= h
            body.append(f"<rect x='{MARGIN + i * step + 20}' y='{y}' "
                        f"width='{step - 60}' height='{h}' fill='{palette.get(stage, '#999')}'/>")
            if count:
                body.append(f"<text x='{MARGIN + i * step + 24}' y='{y + 12}' {FONT} "
                            f"fill='#fff'>{stage}:{count}</text>")
        body.append(f"<text x='{MARGIN + i * step + 20}' y='{H - 42}' {FONT}>{c}</text>")
    body.append(f"<text x='{MARGIN}' y='{H - 12}' {FONT} fill='#666'>"
                f"stage = first rung the episode failed (1 hazard ... 7 outcome; None = all reached)</text>")
    return _svg("\n".join(body))


def all_figures(results):
    return {"contrasts": figure_contrasts(results),
            "shortfall": figure_shortfall(results),
            "ladder": figure_ladder(results)}
